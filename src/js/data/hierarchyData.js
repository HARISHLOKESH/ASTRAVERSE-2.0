// Helper lookup function for any object across all hierarchy levels
export function getAstronomicalObject(id) {
  if (hierarchyData.universe.id === id) return hierarchyData.universe;
  const inGalaxies = hierarchyData.galaxies.find(g => g.id === id);
  if (inGalaxies) return inGalaxies;
  const inSystems = hierarchyData.systems.find(s => s.id === id);
  if (inSystems) return inSystems;
  const inStars = hierarchyData.stars.find(st => st.id === id);
  if (inStars) return inStars;
  const inPlanets = hierarchyData.planets.find(p => p.id === id);
  if (inPlanets) return inPlanets;
  const inMoons = hierarchyData.moons.find(m => m.id === id);
  if (inMoons) return inMoons;
  return null;
}

// Get all children for a parent ID
export function getChildrenOf(parentId) {
  if (!parentId || parentId === "universe") {
    return hierarchyData.galaxies;
  }
  const parent = getAstronomicalObject(parentId);
  if (!parent || !parent.childrenIds) return [];
  return parent.childrenIds.map(id => getAstronomicalObject(id)).filter(Boolean);
}

